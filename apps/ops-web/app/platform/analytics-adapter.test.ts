import { webcrypto, createHash } from "node:crypto";
import { parseHTML } from "linkedom";
import { afterEach, expect, it, vi } from "vitest";
import { analyticsContent, trackAnalytics, webAnalytics } from "./analytics";

afterEach(() => { vi.unstubAllGlobals(); });

it("loads Google only after consent, hashes catalogue IDs, and renews identity without duplicating the Google loader", async () => {
  const dom = parseHTML("<html><head></head><body></body></html>");
  const memory = new Map<string, string>();
  const randomSamples = [[4294967295, 1234567890], [2147483648, 987654321]];
  const randomValues = vi.fn((target: Uint32Array) => { target.set(randomSamples.shift()!); return target; });
  vi.stubGlobal("window", dom.window); vi.stubGlobal("document", dom.window.document); vi.stubGlobal("navigator", {});
  vi.stubGlobal("crypto", { subtle: webcrypto.subtle, randomUUID: webcrypto.randomUUID.bind(webcrypto), getRandomValues: randomValues });
  Object.defineProperty(window, "localStorage", { value: { getItem: (key: string) => memory.get(key) ?? null, setItem: (key: string, value: string) => { memory.set(key, value); } } });
  Object.defineProperty(window, "location", { value: { hostname: "flixify.vip", search: "?session_id=cs_private&code=PRIVATE" } });
  Object.defineProperty(document, "cookie", { configurable: true, get: () => "", set: () => {} });
  const fetcher = vi.fn(async () => ({ ok: true, json: async () => ({ schema: 1, consentVersion: 1, web: { enabled: true, measurementId: "G-TEST123456" } }) }));
  vi.stubGlobal("fetch", fetcher);
  const runtime = webAnalytics()!; runtime.page("/filmler?q=PRIVATE");
  trackAnalytics("login");
  expect(document.querySelector("script")).toBeNull(); expect(fetcher).not.toHaveBeenCalled(); expect(randomValues).not.toHaveBeenCalled();
  const loading = runtime.setConsent("accepted");
  for (let index = 0; index < 6; index++) await Promise.resolve();
  const script = document.querySelector("script")!;
  expect(script.src).toBe("https://www.googletagmanager.com/gtag/js?id=G-TEST123456&l=flixifyAnalyticsLayer");
  expect(script.referrerPolicy).toBe("no-referrer");
  script.dispatchEvent(new dom.window.Event("load")); await loading;
  expect(randomValues).not.toHaveBeenCalled();
  const fields = analyticsContent({ kind: "movie", id: "123" });
  expect(await fields.content_id).toBe(createHash("sha256").update("movie:123").digest("hex").slice(0, 24));
  expect(await analyticsContent({ kind: "movie", id: "personal:private-source:movie:123", personalRef: { id: "123" } }).content_id).toBe(await fields.content_id);
  expect(await analyticsContent({ kind: "movie", id: "personal:other-source:movie:123", personalRef: { id: "123" } }).content_id).toBe(await fields.content_id);
  expect(analyticsContent({ kind: "movie", id: "personal:private-source:movie:123" }).content_id).toBeUndefined();
  trackAnalytics("select_content", fields);
  await fields.content_id; for (let index = 0; index < 4; index++) await Promise.resolve();
  const layer = () => ((window as unknown as { flixifyAnalyticsLayer: IArguments[] }).flixifyAnalyticsLayer).map(args => Array.from(args));
  const clientGetter = layer().find(args => args[0] === "get" && args[2] === "client_id")?.[3] as (value: string) => void;
  clientGetter("123456.789012");
  const sessionGetter = layer().find(args => args[0] === "get" && args[2] === "session_id")?.[3] as (value: string) => void;
  sessionGetter("1700000000");
  expect(runtime.attribution()).toMatchObject({ clientId: "123456.789012", sessionId: 1700000000 });
  expect(layer().find(args => args[0] === "event" && args[1] === "select_content")?.[2]).toMatchObject({ content_id: createHash("sha256").update("movie:123").digest("hex").slice(0, 24) });
  expect(JSON.stringify(layer())).not.toContain("PRIVATE"); expect(JSON.stringify(layer())).not.toContain("cs_private");
  await runtime.setConsent("rejected");
  expect((window as unknown as Record<string, unknown>)["ga-disable-G-TEST123456"]).toBe(true);
  const renewed = runtime.setConsent("accepted");
  for (let index = 0; index < 6; index++) await Promise.resolve();
  if (document.querySelector("script") !== script) document.querySelector("script")?.dispatchEvent(new dom.window.Event("load"));
  await renewed;
  expect(document.querySelector("script")).toBe(script);
  const firstReset = (layer().find(args => args[0] === "config")?.[2] as { client_id: string }).client_id;
  expect(firstReset).toBe("4294967295.1234567890");
  expect(firstReset).toMatch(/^\d{1,10}\.\d{1,10}$/);
  expect(randomValues).toHaveBeenCalledTimes(1);
  expect(randomValues.mock.calls[0][0]).toBeInstanceOf(Uint32Array);
  expect(randomValues.mock.calls[0][0]).toHaveLength(2);
  await runtime.setConsent("rejected");
  expect(runtime.attribution()).toBeUndefined();
  await runtime.setConsent("accepted");
  const nextReset = (layer().find(args => args[0] === "config")?.[2] as { client_id: string }).client_id;
  expect(nextReset).toBe("2147483648.987654321");
  expect(nextReset).not.toBe(firstReset);
  expect(randomValues).toHaveBeenCalledTimes(2);
  expect(document.querySelector("script")).toBe(script);
});
